"""生成对抗性测试所需的合成收据图片。

每张图片模拟不同的欺诈场景，配合 mock OCR 响应使用。
"""

from PIL import Image, ImageDraw, ImageFont
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent / "test_receipts"


def _draw_text(draw: ImageDraw.ImageDraw, lines: list[str], y_start: int = 30):
    y = y_start
    for line in lines:
        draw.text((30, y), line, fill="black")
        y += 22


def make_normal():
    """已有 test发票.jpg，跳过。"""
    pass


def make_tampered():
    """金额被篡改的收据：行项合计 != 总额。"""
    img = Image.new("RGB", (400, 500), "white")
    draw = ImageDraw.Draw(img)
    _draw_text(draw, [
        "TAMPERED RECEIPT",
        "========================",
        "Merchant: FakeShop Ltd",
        "Date: 2025-01-15",
        "Country: AU",
        "",
        "Item 1: Widget       $10.00",
        "Item 2: Gadget       $25.00",
        "------------------------",
        "Subtotal:            $35.00",
        "GST (10%):            $3.50",
        "TOTAL:              $135.00",  # 篡改：应该是 38.50
        "",
        "*** Amount altered ***",
    ])
    path = BASE / "tampered" / "amount_tampered.png"
    img.save(path)
    print(f"  Created: {path}")


def make_ai_generated():
    """AI 生成的假收据。"""
    img = Image.new("RGB", (400, 500), "#fefefe")
    draw = ImageDraw.Draw(img)
